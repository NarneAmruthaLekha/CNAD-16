
from contextlib import asynccontextmanager
from pathlib import Path

import joblib
import numpy as np
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, ConfigDict, Field, StrictInt
from sklearn.tree import DecisionTreeClassifier

MODEL_PATH = Path(__file__).resolve().parent / "model.joblib"

RISK_ORDER = {
    "LOW": 1,
    "MEDIUM": 2,
    "HIGH": 3
}

model = None


class RiskRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    changed_files: StrictInt = Field(ge=0)
    lines_added: StrictInt = Field(default=0, ge=0)
    lines_deleted: StrictInt = Field(default=0, ge=0)
    complexity: StrictInt = Field(default=1, ge=1, le=5)


def train_model():
    x = np.array([
        [1, 10, 5, 1],
        [2, 20, 10, 2],
        [3, 40, 15, 2],
        [5, 120, 30, 3],
        [8, 250, 100, 4],
        [12, 500, 200, 5],
        [2, 5, 2, 1],
        [6, 180, 80, 4],
        [10, 350, 150, 5],
        [4, 60, 20, 2],
        [2, 889, 324, 5],
        [5, 700, 300, 5],
        [8, 1000, 500, 5],
        [12, 1500, 800, 5],
        [15, 2000, 1000, 5],
        [10, 100, 50, 2],
        [3, 300, 200, 4],
        [1, 600, 400, 5]
    ], dtype=np.int64)

    y = np.array([
        "LOW", "LOW", "LOW", "MEDIUM", "HIGH", "HIGH",
        "LOW", "HIGH", "HIGH", "MEDIUM", "HIGH", "HIGH",
        "HIGH", "HIGH", "HIGH", "MEDIUM", "HIGH", "HIGH"
    ])

    trained_model = DecisionTreeClassifier(
        max_depth=4,
        random_state=42
    )
    trained_model.fit(x, y)
    joblib.dump(trained_model, MODEL_PATH)
    return trained_model


def load_model():
    if not MODEL_PATH.exists():
        return train_model()

    try:
        loaded_model = joblib.load(MODEL_PATH)
        if not hasattr(loaded_model, "predict") or not hasattr(
            loaded_model, "predict_proba"
        ):
            raise ValueError("Saved file is not a valid prediction model.")
        if getattr(loaded_model, "n_features_in_", None) != 4:
            raise ValueError("Saved model must accept four input features.")
        return loaded_model
    except (OSError, ValueError, EOFError, AttributeError):
        return train_model()


@asynccontextmanager
async def lifespan(app: FastAPI):
    global model
    model = load_model()
    yield
    model = None


app = FastAPI(
    title="ImpactFlow Risk Prediction Service",
    version="1.0.0",
    lifespan=lifespan
)


@app.get("/health")
def health():
    return {
        "status": "UP" if model is not None else "DOWN",
        "service": "risk-prediction-service",
        "model_loaded": model is not None
    }


@app.post("/predict")
def predict(request: RiskRequest):
    if model is None:
        raise HTTPException(
            status_code=503,
            detail="Risk prediction model is not available."
        )

    features = np.array([[
        request.changed_files,
        request.lines_added,
        request.lines_deleted,
        request.complexity
    ]], dtype=np.int64)

    try:
        prediction = str(model.predict(features)[0])
        probabilities = model.predict_proba(features)[0]
        classes = model.classes_

        score = sum(
            float(probability) * RISK_ORDER[str(label)]
            for label, probability in zip(classes, probabilities)
        ) / 3.0

        return {
            "risk": prediction,
            "risk_score": round(float(score), 3),
            
            "message": (
                "Prediction generated by the decision tree model. "
                "The score is model-derived, not a calibrated "
                "probability of software failure."
            )
        }
    except (ValueError, TypeError, KeyError) as exc:
        raise HTTPException(
            status_code=500,
            detail="Unable to generate the risk prediction."
        ) from exc
